/**
 * Generates `src/icons/registry.ts` from the SVG sources in `icons/`.
 *
 *  icons/vuesax/*.svg   exported verbatim from the PearDrop Figma file (Vuesax set)
 *  icons/pearkit/*.svg  extra glyphs drawn on the same 24px / 1.5px grid
 *
 * Colours in the sources are ignored: every stroke/fill becomes the icon's
 * `color` prop at render time, which is what makes icons themeable.
 *
 *   npm run icons
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, basename, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sets = ['vuesax', 'pearkit'];
const attr = (tag, name) => tag.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];

const icons = {};
for (const set of sets) {
  const dir = join(root, 'icons', set);
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
    const svg = readFileSync(join(dir, file), 'utf8');
    const paths = [...svg.matchAll(/<path\b[^>]*\/>/g)].map(([tag]) => {
      const p = { d: attr(tag, 'd') };
      if (attr(tag, 'stroke')) {
        p.stroke = true;
        p.strokeWidth = Number(attr(tag, 'stroke-width') ?? 1.5);
        const cap = attr(tag, 'stroke-linecap');
        const join = attr(tag, 'stroke-linejoin');
        const miter = attr(tag, 'stroke-miterlimit');
        if (cap) p.strokeLinecap = cap;
        if (join) p.strokeLinejoin = join;
        if (miter) p.strokeMiterlimit = Number(miter);
      }
      const fill = attr(tag, 'fill');
      if (fill && fill !== 'none') p.fill = true;
      return p;
    });
    icons[basename(file, '.svg')] = { set, paths };
  }
}

const names = Object.keys(icons);
const out = `/* eslint-disable */
// AUTO-GENERATED by scripts/build-icons.mjs — do not edit by hand. Run \`npm run icons\`.

export interface IconPath {
  d: string;
  stroke?: boolean;
  fill?: boolean;
  strokeWidth?: number;
  strokeLinecap?: 'round' | 'butt' | 'square';
  strokeLinejoin?: 'round' | 'miter' | 'bevel';
  strokeMiterlimit?: number;
}

export interface IconDefinition {
  /** Where the glyph comes from: \`vuesax\` (Figma) or \`pearkit\` (drawn for the kit). */
  set: 'vuesax' | 'pearkit';
  paths: IconPath[];
}

export const iconRegistry = ${JSON.stringify(icons, null, 2)} as const satisfies Record<string, IconDefinition>;

export type IconName = keyof typeof iconRegistry;

export const iconNames = ${JSON.stringify(names)} as IconName[];
`;
writeFileSync(join(root, 'src/icons/registry.ts'), out);
console.log(`Generated ${names.length} icons → src/icons/registry.ts`);
